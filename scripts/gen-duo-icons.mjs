// Regenerates src/components/icons/duo-paths.ts: only the Phosphor "duotone" artwork of the icons
// that src/components/icons/duo.tsx uses. Importing the Phosphor components ships all six weights of
// every icon to the browser (~47 KB gzipped on each page); this keeps one weight (~a few KB).
// Run after adding an icon to duo.tsx:  node scripts/gen-duo-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";

const require = createRequire(import.meta.url);
const src = readFileSync("src/components/icons/duo.tsx", "utf8");
const names = [...new Set([...src.matchAll(/duo\("([A-Za-z]+)"/g)].map((m) => m[1]))].sort();
const defsDir = require.resolve("@phosphor-icons/react").replace(/dist\/.*$/, "dist/defs/");

const out = {};
for (const name of names) {
  const mod = await import(pathToFileURL(`${defsDir}${name}.es.js`).href);
  const weights = Object.values(mod).find((v) => v instanceof Map);
  const frag = weights.get("duotone");
  const kids = [].concat(frag.props.children).filter(Boolean);
  out[name] = kids.map((el) => {
    const { children: _children, ...props } = el.props; // eslint-disable-line @typescript-eslint/no-unused-vars
    return [el.type, props];
  });
}

const body = Object.entries(out)
  .map(([n, els]) => `  ${n}: ${JSON.stringify(els)},`)
  .join("\n");
writeFileSync(
  "src/components/icons/duo-paths.ts",
  `// Generated by scripts/gen-duo-icons.mjs from @phosphor-icons/react (MIT). Do not edit by hand.\n` +
    `export type DuoEl = [string, Record<string, string | number>];\n` +
    `export const DUO_PATHS: Record<string, DuoEl[]> = {\n${body}\n};\n`,
);
console.log(`${names.length} icons written`);
