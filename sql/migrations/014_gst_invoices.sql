ALTER TABLE products
  ADD COLUMN hsn VARCHAR(10) NULL AFTER seo_description,
  ADD COLUMN gst_rate DECIMAL(4,2) NULL AFTER hsn;

CREATE TABLE invoice_sequences (
  fy VARCHAR(9) NOT NULL PRIMARY KEY,
  next_seq INT UNSIGNED NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE invoices (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  order_id INT UNSIGNED NOT NULL UNIQUE,
  invoice_no VARCHAR(32) NOT NULL UNIQUE,
  fy VARCHAR(9) NOT NULL,
  seq INT UNSIGNED NOT NULL,
  snapshot JSON NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_invoices_fy_seq (fy, seq),
  CONSTRAINT fk_invoices_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
